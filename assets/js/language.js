function normalizeTranslationKey(value) {
  return value.replace(/\s+/g, " ").trim();
}

function preserveWhitespace(original, translated) {
  const leading = original.match(/^\s*/)[0];
  const trailing = original.match(/\s*$/)[0];
  return `${leading}${translated}${trailing}`;
}

const translatableText = [];
const textWalker = document.createTreeWalker(document.documentElement, NodeFilter.SHOW_TEXT);

while (textWalker.nextNode()) {
  const node = textWalker.currentNode;
  const original = node.nodeValue;
  const key = normalizeTranslationKey(original);

  if (bengaliTranslations.has(key)) {
    translatableText.push({ node, original, key });
  }
}

const translatableAttributes = [];
const attributeNames = ["alt", "aria-label", "placeholder", "content", "title"];

for (const element of document.querySelectorAll("[alt], [aria-label], [placeholder], [content], [title]")) {
  for (const attributeName of attributeNames) {
    const original = element.getAttribute(attributeName);

    if (original && bengaliTranslations.has(normalizeTranslationKey(original))) {
      translatableAttributes.push({
        element,
        attributeName,
        original,
        key: normalizeTranslationKey(original),
      });
    }
  }
}

let currentLanguage = "en";

try {
  currentLanguage = localStorage.getItem("portfolioLanguage") === "bn" ? "bn" : "en";
} catch (error) {
  console.error("Could not read the saved language preference.", error);
}

function translate(message) {
  return currentLanguage === "bn" ? bengaliTranslations.get(message) || message : message;
}

function applyLanguage(language) {
  if (language !== "en" && language !== "bn") {
    throw new Error(`Unsupported portfolio language: ${language}`);
  }

  currentLanguage = language;
  document.documentElement.lang = language;

  for (const entry of translatableText) {
    const translated = language === "bn" ? bengaliTranslations.get(entry.key) : entry.key;
    entry.node.nodeValue = preserveWhitespace(entry.original, translated);
  }

  for (const entry of translatableAttributes) {
    const translated = language === "bn" ? bengaliTranslations.get(entry.key) : entry.original;
    entry.element.setAttribute(entry.attributeName, translated);
  }

  for (const button of document.querySelectorAll("[data-language]")) {
    button.setAttribute("aria-pressed", String(button.dataset.language === language));
  }

  document.dispatchEvent(new CustomEvent("portfolio-language-change", { detail: { language } }));
}

window.portfolioTranslate = translate;

for (const button of document.querySelectorAll("[data-language]")) {
  button.addEventListener("click", function () {
    applyLanguage(button.dataset.language);

    try {
      localStorage.setItem("portfolioLanguage", currentLanguage);
    } catch (error) {
      console.error("Could not save the language preference.", error);
    }
  });
}

applyLanguage(currentLanguage);
